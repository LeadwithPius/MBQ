CREATE TABLE blood_stock_movement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    stock_id BIGINT NOT NULL
        REFERENCES blood_stock(id),

    movement_type VARCHAR(30) NOT NULL,

    units_changed INTEGER NOT NULL
        CHECK (units_changed > 0),

    quantity_before INTEGER NOT NULL
        CHECK (quantity_before >= 0),

    quantity_after INTEGER NOT NULL
        CHECK (quantity_after >= 0),

    reason VARCHAR(500),

    recorded_by BIGINT
        REFERENCES staff_user(id),

    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_blood_movement_type
        CHECK (
            movement_type IN (
                'RECEIVED',
                'ISSUED',
                'EXPIRED',
                'WASTED',
                'TRANSFER_IN',
                'TRANSFER_OUT',
                'ADJUSTMENT_IN',
                'ADJUSTMENT_OUT'
            )
        )
);

CREATE INDEX idx_blood_movement_stock_date
    ON blood_stock_movement(stock_id, created_at);