CREATE TABLE triage_observation (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id BIGINT NOT NULL REFERENCES patient(id),
  queue_ticket_id BIGINT REFERENCES queue_ticket(id),
  assessed_by_id BIGINT NOT NULL REFERENCES staff_user(id),
  measured_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  systolic_bp INTEGER CHECK (systolic_bp IS NULL OR systolic_bp BETWEEN 30 AND 300),
  diastolic_bp INTEGER CHECK (diastolic_bp IS NULL OR diastolic_bp BETWEEN 20 AND 200),
  heart_rate INTEGER CHECK (heart_rate IS NULL OR heart_rate BETWEEN 1 AND 300),
  respiratory_rate INTEGER CHECK (respiratory_rate IS NULL OR respiratory_rate BETWEEN 1 AND 100),
  temperature_c NUMERIC(4,1) CHECK (temperature_c IS NULL OR temperature_c BETWEEN 25 AND 45),
  spo2_percent INTEGER CHECK (spo2_percent IS NULL OR spo2_percent BETWEEN 0 AND 100),
  symptoms TEXT NOT NULL DEFAULT '',
  notes TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_triage_observation_patient_measured
  ON triage_observation(patient_id, measured_at DESC);
CREATE INDEX idx_triage_observation_queue_ticket
  ON triage_observation(queue_ticket_id);

CREATE TABLE clinical_risk_assessment (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  observation_id BIGINT NOT NULL REFERENCES triage_observation(id),
  recommended_priority VARCHAR(20) NOT NULL
    CHECK (recommended_priority IN ('NORMAL','URGENT','EMERGENCY')),
  findings TEXT NOT NULL,
  assessment_source VARCHAR(40) NOT NULL DEFAULT 'RULES_BASELINE',
  model_version VARCHAR(80) NOT NULL DEFAULT 'RULES_BASELINE_V1',
  clinician_review_required BOOLEAN NOT NULL DEFAULT TRUE,
  review_status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
    CHECK (review_status IN ('PENDING','CONFIRMED','OVERRIDDEN')),
  reviewed_by_id BIGINT REFERENCES staff_user(id),
  clinician_notes TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  reviewed_at TIMESTAMPTZ
);
CREATE INDEX idx_clinical_risk_observation_created
  ON clinical_risk_assessment(observation_id, created_at DESC);
CREATE INDEX idx_clinical_risk_pending
  ON clinical_risk_assessment(review_status, created_at DESC);
