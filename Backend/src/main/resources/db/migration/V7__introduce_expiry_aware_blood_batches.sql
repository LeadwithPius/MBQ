-- Introduce batch-level traceability without discarding the existing stock aggregate.
-- Existing aggregate balances have no trustworthy expiry metadata. Backfill them as
-- unverified legacy batches so they remain visible but cannot be issued by FEFO.

CREATE TABLE blood_stock_batch (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    stock_id BIGINT NOT NULL
        REFERENCES blood_stock(id) ON DELETE RESTRICT,

    batch_reference VARCHAR(100) NOT NULL,

    expiry_date DATE,

    opening_quantity INTEGER NOT NULL
        CHECK (opening_quantity >= 0),

    remaining_quantity INTEGER NOT NULL
        CHECK (
            remaining_quantity >= 0
            AND remaining_quantity <= opening_quantity
        ),

    verification_status VARCHAR(30) NOT NULL
        CHECK (verification_status IN ('VERIFIED', 'UNVERIFIED_LEGACY')),

    source_reference VARCHAR(255),

    recorded_by BIGINT
        REFERENCES staff_user(id) ON DELETE SET NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_blood_stock_batch_reference
        UNIQUE (stock_id, batch_reference),

    CONSTRAINT chk_blood_batch_expiry_verification
        CHECK (
            (verification_status = 'UNVERIFIED_LEGACY' AND expiry_date IS NULL)
            OR
            (verification_status = 'VERIFIED' AND expiry_date IS NOT NULL)
        )
);

CREATE INDEX idx_blood_batch_fefo
    ON blood_stock_batch(stock_id, expiry_date, id)
    WHERE verification_status = 'VERIFIED' AND remaining_quantity > 0;

CREATE INDEX idx_blood_batch_stock_status
    ON blood_stock_batch(stock_id, verification_status, remaining_quantity);

-- The existing balance is retained exactly. Its origin and expiry are unknown,
-- so it is represented as a quarantined/unverified opening balance.
INSERT INTO blood_stock_batch (
    stock_id,
    batch_reference,
    expiry_date,
    opening_quantity,
    remaining_quantity,
    verification_status,
    source_reference
)
SELECT
    id,
    'LEGACY-OPENING-' || id,
    NULL,
    units_available,
    units_available,
    'UNVERIFIED_LEGACY',
    'Opening balance migrated from blood_stock; expiry and provenance unverified.'
FROM blood_stock;

-- Extend the existing movement ledger. Nullable fields preserve all historical rows.
ALTER TABLE blood_stock_movement
    ADD COLUMN batch_id BIGINT
        REFERENCES blood_stock_batch(id) ON DELETE RESTRICT,
    ADD COLUMN idempotency_key VARCHAR(120),
    ADD COLUMN request_fingerprint VARCHAR(128),
    ADD COLUMN transfer_id UUID;

-- A key is unique across the ledger. For a transfer, store it on one canonical
-- movement row and use transfer_id to correlate the paired debit/credit rows.
CREATE UNIQUE INDEX uq_blood_movement_idempotency_key
    ON blood_stock_movement(idempotency_key)
    WHERE idempotency_key IS NOT NULL;

CREATE INDEX idx_blood_movement_transfer
    ON blood_stock_movement(transfer_id)
    WHERE transfer_id IS NOT NULL;

-- New and historical movement rows are immutable. Corrections are compensating
-- movements, never UPDATE/DELETE operations.
CREATE OR REPLACE FUNCTION prevent_blood_stock_movement_mutation()
RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'blood_stock_movement is append-only; record a compensating movement';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_blood_stock_movement_immutable
BEFORE UPDATE OR DELETE ON blood_stock_movement
FOR EACH ROW
EXECUTE FUNCTION prevent_blood_stock_movement_mutation();
