CREATE TABLE facility (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      VARCHAR(255) NOT NULL,
    location  VARCHAR(255)
);

CREATE TABLE department (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    facility_id BIGINT NOT NULL REFERENCES facility(id)
);

CREATE TABLE staff_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(255) NOT NULL,
    username      VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role          VARCHAR(255) NOT NULL,
    active        BOOLEAN NOT NULL,
    department_id BIGINT REFERENCES department(id)
);

CREATE TABLE patient (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    age         INTEGER,
    sex         VARCHAR(255),
    contact     VARCHAR(255),
    blood_group VARCHAR(255),
    facility_id BIGINT REFERENCES facility(id)
);

CREATE TABLE queue_ticket (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_number   VARCHAR(255) NOT NULL,
    patient_id      BIGINT NOT NULL REFERENCES patient(id),
    department_id   BIGINT NOT NULL REFERENCES department(id),
    priority_level  VARCHAR(255) NOT NULL,
    status          VARCHAR(255) NOT NULL,
    time_issued     TIMESTAMP(6) NOT NULL,
    triage_notes    VARCHAR(255),
    outcome         VARCHAR(255),
    requires_blood  BOOLEAN NOT NULL
);
CREATE INDEX idx_ticket_dept_status ON queue_ticket(department_id, status);

CREATE TABLE blood_stock (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    facility_id         BIGINT NOT NULL REFERENCES facility(id),
    blood_group         VARCHAR(255) NOT NULL,
    units_available     INTEGER NOT NULL,
    low_stock_threshold INTEGER NOT NULL,
    last_updated        TIMESTAMP(6),
    UNIQUE (facility_id, blood_group)
);

CREATE TABLE donor (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    blood_group VARCHAR(255) NOT NULL,
    contact     VARCHAR(255),
    eligible    BOOLEAN NOT NULL
);

CREATE TABLE alert (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_id        BIGINT NOT NULL REFERENCES blood_stock(id),
    donor_id        BIGINT NOT NULL REFERENCES donor(id),
    date_sent       TIMESTAMP(6),
    response_status VARCHAR(255)
);
