-- Blood donations (brief section 9). A donation is collected, then screened.
-- Only a PASSED donation becomes stock: it is received as a batch through the normal
-- inventory path (ledger movement, idempotency) and still needs batch verification
-- before it can be issued.
CREATE TABLE blood_donation (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    donor_id        BIGINT NOT NULL REFERENCES donor(id) ON DELETE RESTRICT,
    facility_id     BIGINT NOT NULL REFERENCES facility(id) ON DELETE RESTRICT,
    blood_group     VARCHAR(20) NOT NULL,
    units           INTEGER NOT NULL DEFAULT 1,
    collected_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    collected_by    BIGINT NOT NULL REFERENCES staff_user(id) ON DELETE RESTRICT,
    status          VARCHAR(20) NOT NULL DEFAULT 'COLLECTED',
    screened_by     BIGINT REFERENCES staff_user(id) ON DELETE RESTRICT,
    screened_at     TIMESTAMPTZ,
    screening_notes VARCHAR(1000),
    batch_id        BIGINT UNIQUE REFERENCES blood_stock_batch(id) ON DELETE RESTRICT,
    CONSTRAINT chk_donation_units CHECK (units BETWEEN 1 AND 2),
    CONSTRAINT chk_donation_status CHECK (status IN ('COLLECTED', 'PASSED', 'FAILED')),
    CONSTRAINT chk_donation_blood_group CHECK (
        blood_group IN ('A_POS', 'A_NEG', 'B_POS', 'B_NEG', 'AB_POS', 'AB_NEG', 'O_POS', 'O_NEG')),
    CONSTRAINT chk_donation_screening CHECK (
        (status = 'COLLECTED' AND screened_at IS NULL AND batch_id IS NULL)
        OR (status = 'FAILED' AND screened_at IS NOT NULL AND screened_by IS NOT NULL AND batch_id IS NULL)
        OR (status = 'PASSED' AND screened_at IS NOT NULL AND screened_by IS NOT NULL AND batch_id IS NOT NULL)
    )
);

CREATE INDEX idx_donation_donor_collected ON blood_donation (donor_id, collected_at DESC);
CREATE INDEX idx_donation_facility_status ON blood_donation (facility_id, status, collected_at DESC);

-- V10 made donors facility-scoped but left existing donors unassigned. When the
-- installation has exactly one facility the owner is unambiguous, so assign it;
-- with several facilities, donors stay unassigned for an administrator to decide.
UPDATE donor
SET facility_id = (SELECT MIN(id) FROM facility)
WHERE facility_id IS NULL
  AND (SELECT COUNT(*) FROM facility) = 1;
