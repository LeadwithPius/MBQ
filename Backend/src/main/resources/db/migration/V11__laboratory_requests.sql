-- Laboratory investigations requested from a doctor's consultation (brief section 7).
-- Results can only be recorded once, by the lab, and are linked to the same patient
-- as the consultation, so a result can never be attached to the wrong patient.
CREATE TABLE lab_request (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consultation_id  BIGINT NOT NULL REFERENCES consultation(id) ON DELETE RESTRICT,
    patient_id       BIGINT NOT NULL REFERENCES patient(id) ON DELETE RESTRICT,
    facility_id      BIGINT NOT NULL REFERENCES facility(id) ON DELETE RESTRICT,
    test_name        VARCHAR(120) NOT NULL,
    clinical_notes   VARCHAR(1000),
    priority         VARCHAR(20) NOT NULL DEFAULT 'ROUTINE',
    status           VARCHAR(20) NOT NULL DEFAULT 'REQUESTED',
    requested_by     BIGINT NOT NULL REFERENCES staff_user(id) ON DELETE RESTRICT,
    requested_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_by       BIGINT REFERENCES staff_user(id) ON DELETE RESTRICT,
    started_at       TIMESTAMPTZ,
    result_text      VARCHAR(4000),
    result_notes     VARCHAR(2000),
    abnormal         BOOLEAN,
    completed_by     BIGINT REFERENCES staff_user(id) ON DELETE RESTRICT,
    completed_at     TIMESTAMPTZ,
    cancelled_reason VARCHAR(500),
    CONSTRAINT chk_lab_priority CHECK (priority IN ('ROUTINE', 'URGENT')),
    CONSTRAINT chk_lab_status CHECK (status IN ('REQUESTED', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT chk_lab_test_name CHECK (LENGTH(TRIM(test_name)) > 0),
    -- A result exists exactly when the request is completed.
    CONSTRAINT chk_lab_result_when_completed CHECK (
        (status = 'COMPLETED' AND result_text IS NOT NULL AND completed_by IS NOT NULL AND completed_at IS NOT NULL)
        OR (status <> 'COMPLETED' AND result_text IS NULL AND completed_at IS NULL)
    )
);

-- The same test cannot be open twice for one consultation (duplicate request protection).
CREATE UNIQUE INDEX uq_lab_request_open_test
    ON lab_request (consultation_id, LOWER(TRIM(test_name)))
    WHERE status IN ('REQUESTED', 'IN_PROGRESS');

CREATE INDEX idx_lab_request_facility_status ON lab_request (facility_id, status, requested_at);
CREATE INDEX idx_lab_request_patient ON lab_request (patient_id, requested_at DESC);
CREATE INDEX idx_lab_request_consultation ON lab_request (consultation_id);
