-- Each ticket number must be unique.
CREATE UNIQUE INDEX uq_queue_ticket_ticket_number
    ON queue_ticket (ticket_number);

-- Atomic ticket-number counters, separated by facility, department and date.
CREATE TABLE queue_ticket_sequence (
    facility_id BIGINT NOT NULL REFERENCES facility(id),
    department_id BIGINT NOT NULL REFERENCES department(id),
    issue_date DATE NOT NULL,
    last_number INTEGER NOT NULL CHECK (last_number > 0),

    PRIMARY KEY (facility_id, department_id, issue_date)
);

-- Record every status transition for operational traceability.
CREATE TABLE queue_ticket_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    ticket_id BIGINT NOT NULL
        REFERENCES queue_ticket(id) ON DELETE RESTRICT,

    previous_status VARCHAR(30),

    new_status VARCHAR(30) NOT NULL
        CHECK (
            new_status IN (
                'WAITING',
                'IN_PROGRESS',
                'COMPLETED',
                'CANCELLED'
            )
        ),

    changed_by BIGINT
        REFERENCES staff_user(id) ON DELETE SET NULL,

    changed_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    notes VARCHAR(255)
);

CREATE INDEX idx_queue_history_ticket_time
    ON queue_ticket_status_history (ticket_id, changed_at, id);