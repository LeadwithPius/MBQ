-- Formal clinical blood request lifecycle.
-- Doctors and nurses request units for a patient; lab staff/admin review and fulfil.
CREATE TABLE blood_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    facility_id BIGINT NOT NULL REFERENCES facility(id) ON DELETE RESTRICT,
    patient_id BIGINT NOT NULL REFERENCES patient(id) ON DELETE RESTRICT,
    blood_group VARCHAR(20),
    units INTEGER NOT NULL,
    priority_level VARCHAR(20) NOT NULL DEFAULT 'NORMAL',
    reason VARCHAR(500) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    requested_by BIGINT NOT NULL REFERENCES staff_user(id) ON DELETE RESTRICT,
    requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_by BIGINT REFERENCES staff_user(id) ON DELETE RESTRICT,
    reviewed_at TIMESTAMPTZ,
    review_notes VARCHAR(500),
    fulfilled_at TIMESTAMPTZ,
    stock_id BIGINT REFERENCES blood_stock(id) ON DELETE RESTRICT,
    inventory_operation_id UUID REFERENCES blood_inventory_operation(id) ON DELETE RESTRICT,
    CONSTRAINT chk_blood_request_units CHECK (units BETWEEN 1 AND 10),
    CONSTRAINT chk_blood_request_priority CHECK (priority_level IN ('NORMAL', 'URGENT', 'EMERGENCY')),
    CONSTRAINT chk_blood_request_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'FULFILLED')),
    CONSTRAINT chk_blood_request_review CHECK (
      (status = 'PENDING' AND reviewed_by IS NULL AND reviewed_at IS NULL)
      OR (status IN ('APPROVED', 'REJECTED', 'FULFILLED') AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL)
    ),
    CONSTRAINT chk_blood_request_fulfilment CHECK (
      (status = 'FULFILLED' AND fulfilled_at IS NOT NULL AND stock_id IS NOT NULL AND inventory_operation_id IS NOT NULL)
      OR (status <> 'FULFILLED' AND fulfilled_at IS NULL AND stock_id IS NULL AND inventory_operation_id IS NULL)
    )
);

CREATE INDEX idx_blood_request_facility_status_date
    ON blood_request (facility_id, status, requested_at DESC);
CREATE INDEX idx_blood_request_patient_date
    ON blood_request (patient_id, requested_at DESC);
