-- Preserve clinician decisions separately from the original automated recommendation.
ALTER TABLE clinical_risk_assessment
    ADD COLUMN confirmed_priority VARCHAR(20);

ALTER TABLE clinical_risk_assessment
    ADD CONSTRAINT chk_clinical_risk_confirmed_priority
    CHECK (confirmed_priority IS NULL OR confirmed_priority IN ('NORMAL', 'URGENT', 'EMERGENCY'));

CREATE TABLE clinical_risk_review_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assessment_id BIGINT NOT NULL REFERENCES clinical_risk_assessment(id),
    reviewed_by_id BIGINT NOT NULL REFERENCES staff_user(id),
    review_status VARCHAR(20) NOT NULL
        CHECK (review_status IN ('CONFIRMED', 'OVERRIDDEN')),
    recommended_priority_snapshot VARCHAR(20) NOT NULL
        CHECK (recommended_priority_snapshot IN ('NORMAL', 'URGENT', 'EMERGENCY')),
    confirmed_priority VARCHAR(20)
        CHECK (confirmed_priority IS NULL OR confirmed_priority IN ('NORMAL', 'URGENT', 'EMERGENCY')),
    clinician_notes TEXT NOT NULL,
    reviewed_at TIMESTAMPTZ NOT NULL,
    is_legacy BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT chk_legacy_override_priority
        CHECK (is_legacy OR review_status <> 'OVERRIDDEN' OR confirmed_priority IS NOT NULL),
    CONSTRAINT uq_clinical_risk_review_history_assessment UNIQUE (assessment_id)
);

CREATE INDEX idx_clinical_risk_review_history_assessment_time
    ON clinical_risk_review_history(assessment_id, reviewed_at DESC, id DESC);

-- Historical overrides did not persist their selected priority. Do not fabricate it.
-- Confirmed historical reviews can safely use the recommendation as their confirmed priority.
UPDATE clinical_risk_assessment
   SET confirmed_priority = CASE
       WHEN review_status = 'CONFIRMED' THEN recommended_priority
       ELSE NULL
   END
 WHERE review_status IN ('CONFIRMED', 'OVERRIDDEN');

INSERT INTO clinical_risk_review_history (
    assessment_id,
    reviewed_by_id,
    review_status,
    recommended_priority_snapshot,
    confirmed_priority,
    clinician_notes,
    reviewed_at,
    is_legacy
)
SELECT
    id,
    reviewed_by_id,
    review_status,
    recommended_priority,
    confirmed_priority,
    COALESCE(NULLIF(BTRIM(clinician_notes), ''),
             'Legacy review; clinician notes were not recorded.'),
    COALESCE(reviewed_at, created_at),
    TRUE
FROM clinical_risk_assessment
WHERE review_status IN ('CONFIRMED', 'OVERRIDDEN')
  AND reviewed_by_id IS NOT NULL;

-- Review history is append-only. Corrections must be represented by a new workflow,
-- not by rewriting the audit record.
CREATE OR REPLACE FUNCTION prevent_clinical_risk_review_history_mutation()
RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'clinical_risk_review_history is append-only';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_clinical_risk_review_history_immutable
BEFORE UPDATE OR DELETE ON clinical_risk_review_history
FOR EACH ROW
EXECUTE FUNCTION prevent_clinical_risk_review_history_mutation();
