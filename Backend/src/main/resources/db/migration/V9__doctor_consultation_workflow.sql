CREATE TABLE consultation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL REFERENCES patient(id),
    queue_ticket_id BIGINT NOT NULL UNIQUE REFERENCES queue_ticket(id),
    doctor_id BIGINT NOT NULL REFERENCES staff_user(id),
    presenting_complaint TEXT NOT NULL DEFAULT '',
    history_of_present_illness TEXT,
    medical_history TEXT,
    examination_findings TEXT,
    diagnosis TEXT,
    treatment_plan TEXT,
    prescriptions TEXT,
    investigations TEXT,
    follow_up TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT'
        CHECK (status IN ('DRAFT', 'COMPLETED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ,
    CONSTRAINT chk_consultation_completion_time
        CHECK ((status = 'DRAFT' AND completed_at IS NULL)
            OR (status = 'COMPLETED' AND completed_at IS NOT NULL))
);

CREATE INDEX idx_consultation_patient_created
    ON consultation(patient_id, created_at DESC);

CREATE INDEX idx_consultation_doctor_created
    ON consultation(doctor_id, created_at DESC);
