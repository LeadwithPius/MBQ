-- One idempotency record represents one logical inventory command.
-- A command may generate multiple movement rows (for example, one FEFO issue
-- spanning several batches), so idempotency must not live only on a movement.
CREATE TABLE blood_inventory_operation (
    id UUID PRIMARY KEY,

    idempotency_key VARCHAR(120) NOT NULL,

    operation_type VARCHAR(30) NOT NULL
        CHECK (
            operation_type IN (
                'RECEIVE',
                'ISSUE',
                'TRANSFER',
                'ADJUSTMENT',
                'WASTE',
                'EXPIRE'
            )
        ),

    request_fingerprint VARCHAR(128) NOT NULL,

    result_payload JSONB,

    recorded_by BIGINT
        REFERENCES staff_user(id) ON DELETE SET NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_blood_inventory_operation_idempotency_key
        UNIQUE (idempotency_key)
);

CREATE INDEX idx_blood_inventory_operation_created
    ON blood_inventory_operation(created_at DESC);

-- Link every movement generated by a logical command to its operation.
-- Nullable for historical rows; all new service-created movements will set it.
ALTER TABLE blood_stock_movement
    ADD COLUMN operation_id UUID
        REFERENCES blood_inventory_operation(id) ON DELETE RESTRICT;

CREATE INDEX idx_blood_movement_operation
    ON blood_stock_movement(operation_id, id)
    WHERE operation_id IS NOT NULL;
